export function clientServiceName(slug:string,name:string,lang:Lang):string {
  return lang==='id'?name:services[slug]?.[lang]||name;
}

export function clientStageLabel(label:string, sourceTemplateStepId:string|undefined, lang:Lang):string {
  if (!sourceTemplateStepId || lang==='id') return label;
  const dictionary=lang==='en'?english:chinese;
  return dictionary[label]||label;
}
